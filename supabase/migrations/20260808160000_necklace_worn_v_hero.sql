--                real cast shadow do the work the props were doing.
--   Cropping     Crop the clasp and extender. Accepted knowingly: the adjuster
--                is information a wholesale buyer looks for, and it now lives
--                only in the description bullets.
--   Scope        Replaces the full-length image half. The full-length version
--                stays in prompt history and is one promote away.
--   Waist chain  Unchanged.
--
-- Only the IMAGE half is replaced. The describer's job — a factual identity
-- record of the object — does not change with the pose, and the length-aware
