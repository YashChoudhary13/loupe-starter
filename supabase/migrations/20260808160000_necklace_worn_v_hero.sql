--
--   1. the piece HANGS under gravity; it is not lying on a surface;
--   2. both chain arms fall from the TOP EDGE and are cut off by it — clasp,
--      extender and the top of the loop are out of frame in all six;
--   3. the arms converge into a V or shallow U with the focal element at the
--      single lowest point, centred;
--   4. the V's depth tracks the piece — wide and shallow for a bar or cluster
--      centrepiece, deep and narrow for a long station necklace.
--
-- This also serves the original problem better than full length did. A V cut off
-- by the top edge is unmistakably neck-worn; a closed loop on a surface is not.
--
-- FOUR DECISIONS, ANSWERED BY THE OWNER
--
--   Background   Clean, no props. The samples use ceramic sculptures, a dish
