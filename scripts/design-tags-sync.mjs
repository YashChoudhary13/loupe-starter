#!/usr/bin/env node
/**
 * Copies the design labeller's vocabulary from the search project into Loupe (D177).
 *
 *   node scripts/design-tags-sync.mjs ~/Desktop/Qimati/search/config/taxonomy.json ~/Desktop/Qimati/search/scripts/label.py
 *
 * Writes two files and nothing else:
 *   src/lib/design-tags/vocabulary.ts        what the labeller needs: GUIDE, the kinds' title patterns, every label with
 *                                            its definition, which kinds each type belongs to. The customers' search
 *                                            words and misspellings stay in the search project (this repo is public).
 *   tests/fixtures/design-tags-label-py.json label.py's own system prompt, schema, user text, kind_of, types_for and
 *                                            clean on fixed inputs, run by python3 (no network, no API key), so
 *                                            tests/design-tags.test.ts proves the TypeScript port asks exactly the same.
 *
 * Run it after the search project changes its taxonomy or label.py, then `npx vitest run tests/design-tags.test.ts`.
 */
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const [taxonomyPath, labelPath] = process.argv.slice(2).map(p => resolve(p.replace(/^~(?=\/)/, process.env.HOME ?? '~')))
if (!taxonomyPath || !labelPath) {
  console.error('usage: node scripts/design-tags-sync.mjs <search>/config/taxonomy.json <search>/scripts/label.py')
  process.exit(2)
}
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// ---- label.py: the four constants the request is built from ----
const py = readFileSync(labelPath, 'utf8')
const literal = (name, open, close) => {
  const m = new RegExp(`^${name} = (\\${open}[\\s\\S]*?\\${close})\\s*$`, 'm').exec(py)
  if (!m) throw new Error(`label.py has no ${name} = ${open}…${close}`)
  return JSON.parse(m[1].replace(/,\s*([\]}])/g, '$1'))  // Python literals of plain double-quoted strings are JSON
}
const guide = /^GUIDE = """([\s\S]*?)"""/m.exec(py)?.[1]
if (guide === undefined) throw new Error('label.py has no GUIDE = """…"""')
if (guide.includes('\\')) throw new Error('GUIDE holds a backslash; copy it by hand, this script does not unescape Python strings')
const PIECES = literal('PIECES', '[', ']')
const LIST_FIELDS = literal('LIST_FIELDS', '{', '}')
const FREE_FIELDS = literal('FREE_FIELDS', '[', ']')

// ---- taxonomy.json: definitions only (index 0), and a type's kinds (index 2); never the customer words (index 1) ----
const tax = JSON.parse(readFileSync(taxonomyPath, 'utf8'))
const KINDS = Object.fromEntries(Object.entries(tax.kinds).map(([kind, [pattern]]) => [kind, pattern]))
const FACETS = Object.fromEntries(Object.entries(tax.facets).map(([facet, values]) =>
  [facet, Object.fromEntries(Object.entries(values).map(([label, [definition]]) => [label, definition]))]))
const TYPE_KINDS = Object.fromEntries(Object.entries(tax.facets.type).map(([type, d]) => [type, d[2]]))
for (const key of [...Object.keys(KINDS), ...Object.values(FACETS).flatMap(Object.keys)]) {
  // A key made of digits would be reordered by JavaScript and change the prompt's order.
  if (/^\d+$/.test(key)) throw new Error(`label "${key}" is all digits; JavaScript would move it to the front`)
}
for (const field of Object.values(LIST_FIELDS)) if (!FACETS[field]) throw new Error(`label.py reads facet "${field}", taxonomy.json has none`)

const data = { GUIDE: guide, PIECES, LIST_FIELDS, FREE_FIELDS, KINDS, FACETS, TYPE_KINDS }
const version = createHash('sha256').update(JSON.stringify(data)).digest('hex').slice(0, 12)
const template = s => '`' + s.replace(/[`\\]/g, c => `\\${c}`).replace(/\$\{/g, '\\${') + '`'
const out = `/**
 * GENERATED by scripts/design-tags-sync.mjs from the search project's config/taxonomy.json and scripts/label.py.
 * Do not edit by hand: change those files, then run
 *   node scripts/design-tags-sync.mjs ~/Desktop/Qimati/search/config/taxonomy.json ~/Desktop/Qimati/search/scripts/label.py
 * Only what the labeller sends is copied; the customers' search words stay in the search project (this repo is public).
 */
export const TAXONOMY_VERSION = '${version}'

export const GUIDE = ${template(guide)}

export const PIECES: readonly string[] = ${JSON.stringify(PIECES)}
/** Answer field → the facet whose labels it may use (label.py LIST_FIELDS). */
export const LIST_FIELDS: Readonly<Record<string, string>> = ${JSON.stringify(LIST_FIELDS, null, 2)}
export const FREE_FIELDS: readonly string[] = ${JSON.stringify(FREE_FIELDS)}

/** Kind → title pattern (case-insensitive); the first that matches wins. */
export const KINDS: Readonly<Record<string, string>> = ${JSON.stringify(KINDS, null, 2)}

/** Facet → label → the definition the labeller reads. */
export const FACETS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(FACETS, null, 2)}

/** Type → the kinds (space separated) it can apply to. */
export const TYPE_KINDS: Readonly<Record<string, string>> = ${JSON.stringify(TYPE_KINDS, null, 2)}
`
writeFileSync(resolve(repo, 'src/lib/design-tags/vocabulary.ts'), out)

// ---- the parity fixture: label.py's own functions on fixed inputs ----
const option = (name, ...values) => ({ name, values })
const cases = {
  titles: ['Necklace 970', 'Set (Necklace & Earring) 001', 'Earrings 453', 'Ear Cuffs 001', 'Bracelet Kada 001 (Small)',
    'Kada Bracelet S058', 'Chain Bracelet 353', 'Rings 221', 'Anklets 087 (Single Piece)', 'Hand Chain 104', 'Watch 005',
    'Indian Jewellery 001 (Without chain)', 'Indian Pendant Sets 065', 'Hair Jewellery 001', 'Waist Chain 002', 'Nose Pin 006',
    "Men's Jewellery 001", 'Coin Pouch 001'],
  products: [
    [{ title: 'Necklace 970', options: [option('Color', 'Gold', 'Silver')] }, 'necklace'],
    [{ title: 'Rings 228', options: [option('Size', '6', '7', 'Adjustable')] }, 'ring'],
    [{ title: 'Earrings 453 (Huggies)', options: [] }, 'earrings'],
    [{ title: 'Indian Jewellery 064', options: [option('Number', '1', '2', '3')] }, 'mixed'],
    [{ title: 'Watch 005', options: [option('Color', 'Black / Gold')] }, 'watch'],
    [{ title: 'Facelet 001', options: [] }, 'facelet'],
  ],
  typeKinds: [['necklace'], ['earrings'], ['kada'], ['ring', 'necklace'], ['other']],
  clean: [
    [answer({ pieces: ['necklace', 'necklace'], types: ['pendant', 'stud', 'pendant'], main_motifs: ['heart', 'heart'],
      detail_motifs: ['heart', 'star'], main_colours: ['red'], accent_colours: ['red', 'clear'],
      other_motifs: [' Ghost ', '', 'ghost', '  '], keywords: ['A', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'J'] }), 'necklace'],
    [answer({ pieces: ['necklace', 'earrings'], types: ['pendant', 'stud', 'band', 'cuff'], text_on_piece: ['MOM'] }), 'mixed'],
    [answer({ pieces: [], types: ['band'] }), 'mixed'],
  ],
}
function answer(fields) {
  const empty = Object.fromEntries([...Object.keys(LIST_FIELDS), ...FREE_FIELDS].map(f => [f, []]))
  return { description: 'A test piece.', pieces: [], ...empty, ...fields }
}
const script = `
import json, sys, types
sys.modules.setdefault("anthropic", types.ModuleType("anthropic"))  # label.py needs it only to call the API
sys.path.insert(0, sys.argv[1])
import label
tax = json.load(open(sys.argv[2]))
c = json.load(sys.stdin)
print(json.dumps({
  "system": label.system_prompt(tax),
  "schema": label.schema(tax),
  "kinds": {t: label.kind_of(t, tax) for t in c["titles"]},
  "texts": [label.product_text(p, k, tax) for p, k in c["products"]],
  "types": [label.types_for(k, tax) for k in c["typeKinds"]],
  "clean": [label.clean(o, k, tax) for o, k in c["clean"]],
}, ensure_ascii=False))
`
const run = spawnSync('python3', ['-I', '-c', script, dirname(labelPath), taxonomyPath], { input: JSON.stringify(cases), encoding: 'utf8' })
if (run.status !== 0) throw new Error(`python3 could not run label.py's functions:\n${run.stderr}`)
writeFileSync(resolve(repo, 'tests/fixtures/design-tags-label-py.json'),
  JSON.stringify({ taxonomyVersion: version, cases, expected: JSON.parse(run.stdout) }) + '\n')
console.log(`vocabulary ${version}: ${Object.keys(KINDS).length} kinds, ${Object.values(FACETS).reduce((n, f) => n + Object.keys(f).length, 0)} labels; parity fixture written`)
